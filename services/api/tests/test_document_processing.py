def test_page_map_points_at_each_page_text() -> None:
    records = [
        documents_job.PageRecord(page=1, status="text", text="Birinci sayfa"),
        documents_job.PageRecord(page=2, status="image_only"),
        documents_job.PageRecord(page=3, status="text", text="  Third page  "),
    ]
    text, page_map, truncated = documents_job._build_text(records, "text", 10_000)
    assert not truncated
    assert [entry["page"] for entry in page_map] == [1, 3]
    for entry, expected in zip(page_map, ["Birinci sayfa", "Third page"], strict=True):
        assert text[entry["char_start"] : entry["char_end"]] == expected
    assert text.startswith("[Page 1]\nBirinci sayfa")
    short, short_map, cut = documents_job._build_text(records, "text", 30)
    assert cut
    assert len(short) <= 30
    assert len(short_map) == 1


