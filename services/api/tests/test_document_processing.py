def test_ocr_output_is_a_separate_labelled_record(
    client: TestClient,
    settings: Settings,
    authed: str,
    db_session_factory: sessionmaker[Session],
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Uses a labelled fake engine so the OCR bookkeeping is tested without Tesseract."""
    monkeypatch.setattr(
        documents,
        "ocr_availability",
        lambda _settings: documents.OcrAvailability(True, "fake-engine-0", ("eng", "tur")),
    )
    monkeypatch.setattr(documents, "render_page", lambda _s, _d, page: f"P5 {page}".encode())
    monkeypatch.setattr(
        documents, "ocr_image", lambda _s, image: f"Taranmış sayfa metni {image.decode()[3:]}"
    )
    case = create_case(client, authed)
    pdf = pdf_fixtures.build_pdf(
        [{"text": ["Embedded text layer on page one"]}, {"image": pdf_fixtures.noise_image()}]
    )
    body = _upload(client, authed, case["id"], pdf, ocr="if_needed").json()
    assert _run(db_session_factory, settings, body["job"]["id"]) == "completed"
    job = _job(client, case["id"], body["job"]["id"])
