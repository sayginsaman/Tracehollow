@INTEGRATION
def test_text_pdf_is_extracted_with_page_references_and_indexed_for_ai(
    client: TestClient,
    settings: Settings,
    authed: str,
    db_session_factory: sessionmaker[Session],
) -> None:
    case = create_case(client, authed)
    other = create_case(client, authed, title="Other case")
    with db_session_factory() as db:
        assert (
            db.scalar(select(Case.ai_mode).where(Case.id == uuid.UUID(case["id"]))) == "local_only"
        )
    pdf = pdf_fixtures.text_pdf(
        ["Registry summary for ornek.example", "Registrant: Synthetic Holding"],
        ["Hosting moved to 203.0.113.9 in March"],
    )
    response = _upload(client, authed, case["id"], pdf, ocr="if_needed")
    assert response.status_code == 202, response.text
    body = response.json()
    assert body["evidence"]["kind"] == "pdf"
    assert body["evidence"]["content_type"] == "application/pdf"
    assert body["job"]["options"] == {"ocr": "if_needed"}

    assert _run(db_session_factory, settings, body["job"]["id"]) == "completed"
    job = _job(client, case["id"], body["job"]["id"])
    result = job["result"]
    assert result["document_state"] == "text_extracted"
    assert result["pages_total"] == 2
    assert result["page_status_counts"] == {"text": 2}
    assert result["ocr"]["status"] == "not_needed"
    assert result["parser_versions"]["pypdf"]
    assert [item["page_part"] for item in job["derived_evidence"]] == ["text_layer"]

    derived_id = job["derived_evidence"][0]["id"]
    text = _derived_text(settings, db_session_factory, derived_id)
    detail = client.get(f"/api/v1/cases/{case['id']}/evidence/{derived_id}").json()
    evidence = detail["evidence"]
    assert evidence["derived_from_evidence_id"] == body["evidence"]["id"]
    assert evidence["acquisition_method"] == "authorized_import"
    metadata = evidence["collection_metadata"]
    assert metadata["text_origin"] == "embedded_text_layer"
    assert metadata["source_sha256"] == body["evidence"]["sha256"]
    second_page = metadata["page_map"][1]
    assert second_page["page"] == 2
    assert text[second_page["char_start"] : second_page["char_end"]] == (
        "Hosting moved to 203.0.113.9 in March"
    )

    # The original PDF is never decoded for preview; the derived text is.
    original_preview = client.get(
        f"/api/v1/cases/{case['id']}/evidence/{body['evidence']['id']}/preview"
    ).json()
    assert original_preview["previewable"] is False
    derived_preview = client.get(f"/api/v1/cases/{case['id']}/evidence/{derived_id}/preview").json()
    assert "203.0.113.9" in derived_preview["text"]

    # Case-scoped retrieval finds the extracted text; another case does not.
    with db_session_factory() as db:
        state = db.scalar(
            select(EvidenceIndexState).where(
                EvidenceIndexState.evidence_id == uuid.UUID(derived_id)
            )
        )
        assert state is not None
    run_indexing(settings, db_session_factory, case["id"])
    run_indexing(settings, db_session_factory, other["id"])
    with db_session_factory() as db:
        found = retrieve(db, uuid.UUID(case["id"]), "203.0.113.9 hosting", top_k=5)
        assert found.chunks
        assert found.chunks[0].evidence_id == uuid.UUID(derived_id)
        elsewhere = retrieve(db, uuid.UUID(other["id"]), "203.0.113.9 hosting", top_k=5)
        assert all(chunk.evidence_id != uuid.UUID(derived_id) for chunk in elsewhere.chunks)
    search = client.get(f"/api/v1/cases/{case['id']}/ai/search", params={"q": "203.0.113.9"})
    assert any(hit["evidence_id"] == derived_id for hit in search.json()["hits"])

    # A question in the local-only case is answered locally and cites the page of the PDF.
    conversation = client.post(
        f"/api/v1/cases/{case['id']}/ai/conversations", json={}, headers=browser_headers(authed)
    ).json()
    run = client.post(
        f"/api/v1/cases/{case['id']}/ai/conversations/{conversation['id']}/questions",
        json={"question": "Where was hosting moved in March?"},
        headers=browser_headers(authed),
    ).json()
    assert run["requested_location"] == "local"
    assert run_ai(settings, db_session_factory, run["id"]) == "completed"
    finished = client.get(f"/api/v1/cases/{case['id']}/ai/runs/{run['id']}").json()
    assert finished["processing_location"] == "fixture"
    conversation_url = f"/api/v1/cases/{case['id']}/ai/conversations/{conversation['id']}"
    messages = client.get(conversation_url).json()["messages"]
    answer = next(m for m in messages if m["ai_run_id"] == run["id"] and m["role"] == "assistant")
    cited = [
        citation["citation_id"]
        for claim in answer["answer"]["claims"]
        for citation in claim.get("citations", [])
    ]
    assert cited, answer["answer"]
    passages = [
        client.get(f"/api/v1/cases/{case['id']}/ai/citations/{cid}").json()["passage"]
        for cid in cited
    ]
    on_page_two = [p for p in passages if p and p["evidence_id"] == derived_id]
    assert on_page_two
    assert on_page_two[0]["page"] == 2
    assert on_page_two[0]["text_origin"] == "embedded_text_layer"
    assert on_page_two[0]["derived_from_evidence_id"] == body["evidence"]["id"]
    assert "203.0.113.9" in on_page_two[0]["passage"]


@INTEGRATION
def test_document_states_are_explicit_and_derive_nothing_when_unreadable(
    client: TestClient,
    settings: Settings,
    authed: str,
    db_session_factory: sessionmaker[Session],
) -> None:
    case = create_case(client, authed)
    expectations = [
        (pdf_fixtures.encrypted_pdf(), "pdf_encrypted", "encrypted"),
        (pdf_fixtures.malformed_pdf(), "pdf_malformed", "malformed"),
    ]
    for pdf, code, state in expectations:
        body = _upload(client, authed, case["id"], pdf).json()
        assert _run(db_session_factory, settings, body["job"]["id"]) == "failed"
        job = _job(client, case["id"], body["job"]["id"])
        assert job["status"] == "failed"
        assert job["error_code"] == code
        assert job["result"]["document_state"] == state
        assert job["derived_evidence"] == []
        # The original stays available and intact.
        detail = client.get(f"/api/v1/cases/{case['id']}/evidence/{body['evidence']['id']}")
        assert detail.json()["integrity"]["status"] == "verified"

    owner_only = _upload(client, authed, case["id"], pdf_fixtures.encrypted_pdf("", "owner")).json()
    assert _run(db_session_factory, settings, owner_only["job"]["id"]) == "completed"
    job = _job(client, case["id"], owner_only["job"]["id"])
    assert any("empty user password" in item for item in job["result"]["limitations"])

    refused = _upload(client, authed, case["id"], b"<html><script>alert(1)</script></html>")
    assert refused.status_code == 422
    assert refused.json()["detail"]["code"] == "unsupported_document_type"


