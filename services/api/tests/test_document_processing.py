@INTEGRATION
def test_cancellation_keeps_finished_pages_and_reprocessing_replaces_derived_data(
    client: TestClient,
    settings: Settings,
    authed: str,
    db_session_factory: sessionmaker[Session],
    monkeypatch: pytest.MonkeyPatch,
    no_tesseract: None,
) -> None:
    case = create_case(client, authed)
    pdf = pdf_fixtures.text_pdf(*[[f"Synthetic page {n} body text"] for n in range(1, 26)])
    body = _upload(client, authed, case["id"], pdf).json()
    job_id = body["job"]["id"]

    original = documents.pdf_command
    calls = {"extract": 0}

    def cancel_after_first_batch(
        settings_: Settings, arguments: list[str], document: bytes, **kwargs: Any
    ) -> dict[str, Any]:
        payload = original(settings_, arguments, document, **kwargs)
        if arguments[0] == "extract":
            calls["extract"] += 1
            if calls["extract"] == 1:
                response = client.post(
                    f"/api/v1/cases/{case['id']}/processing-jobs/{job_id}/cancel",
                    headers=browser_headers(authed),
                )
                assert response.status_code == 200, response.text
        return payload

    monkeypatch.setattr(documents, "pdf_command", cancel_after_first_batch)
    assert _run(db_session_factory, settings, job_id) == "canceled"
    monkeypatch.setattr(documents, "pdf_command", original)
    job = _job(client, case["id"], job_id)
    assert job["status"] == "canceled"
    assert job["result"]["pages_processed"] == documents_job.EXTRACT_BATCH_PAGES
    assert any("canceled" in gap for gap in job["result"]["gaps"])
    first_text_id = job["derived_evidence"][0]["id"]
    text = _derived_text(settings, db_session_factory, first_text_id)
    assert "Synthetic page 10 body" in text
    assert "Synthetic page 11 body" not in text

    again = client.post(
        f"/api/v1/cases/{case['id']}/evidence/{body['evidence']['id']}/processing",
        json={"job_type": "document_text", "ocr": "off"},
        headers=browser_headers(authed),
    )
    assert again.status_code == 202, again.text
    assert _run(db_session_factory, settings, again.json()["id"]) == "completed"
    with db_session_factory() as db:
        derived = list(
            db.scalars(
                select(EvidenceObject).where(
                    EvidenceObject.derived_from_evidence_id == uuid.UUID(body["evidence"]["id"])
                )
            )
        )
        assert db.get(EvidenceObject, uuid.UUID(first_text_id)) is None
    assert len(derived) == 1
    assert "Synthetic page 25 body" in _derived_text(
        settings, db_session_factory, str(derived[0].id)
    )
    files = [p for p in settings.evidence_storage_path.rglob("*") if p.is_file()]
    assert len(files) == 2  # the original and the current extracted text


