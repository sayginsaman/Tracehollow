def _context(
    factory: sessionmaker[Session], settings: Settings, **overrides: Any
) -> ProcessingContext:
    return ProcessingContext(
        session_factory=factory,
        storage=EvidenceStorage(settings.evidence_storage_path),
        settings=settings.model_copy(update=overrides) if overrides else settings,
        worker_name="test-worker",
    )


def _upload(client: TestClient, csrf: str, case_id: object, content: bytes, **fields: str) -> Any:
    return client.post(
        f"/api/v1/cases/{case_id}/imports/documents",
        files={"file": (fields.pop("filename", "report.pdf"), content, "application/pdf")},
        data={"import_origin": "Synthetic PDF written by the test suite", **fields},
        headers=browser_headers(csrf),
    )


def _run(factory: sessionmaker[Session], settings: Settings, job_id: str, **overrides: Any) -> str:
    return execute_job(_context(factory, settings, **overrides), uuid.UUID(job_id))


def _job(client: TestClient, case_id: object, job_id: str) -> dict[str, Any]:
    response = client.get(f"/api/v1/cases/{case_id}/processing-jobs/{job_id}")
    assert response.status_code == 200, response.text
    body: dict[str, Any] = response.json()
    return body


def _derived_text(settings: Settings, factory: sessionmaker[Session], evidence_id: str) -> str:
    with factory() as db:
        row = db.get(EvidenceObject, uuid.UUID(evidence_id))
        assert row is not None
        return (
            EvidenceStorage(settings.evidence_storage_path)
            .read_verified(row.storage_key, row.sha256, row.size_bytes)
            .decode()
        )


