    ocr_detail = client.get(
        f"/api/v1/cases/{case['id']}/evidence/{parts['ocr_text']['id']}"
    ).json()["evidence"]
    assert ocr_detail["title"].endswith("OCR text")
    metadata = ocr_detail["collection_metadata"]
    assert metadata["text_origin"] == "ocr"
    assert metadata["engine"]["version"] == "fake-engine-0"
    assert metadata["page_map"][0]["page"] == 2
    assert "Taranmış sayfa metni 2" in _derived_text(
        settings, db_session_factory, parts["ocr_text"]["id"]
    )
    assert "Taranmış" not in _derived_text(settings, db_session_factory, parts["text_layer"]["id"])
    assert job["result"]["ocr_status_counts"] == {"ocr_text": 1}
    assert any("machine recognition" in item for item in job["result"]["limitations"])


